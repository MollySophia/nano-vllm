from __future__ import annotations

import glob
import os
import sys


def _parse_arch(arch: str) -> int:
    arch = arch[: arch.index(".") + 2].replace(".", "")
    return int(arch)


ARCHS = [_parse_arch(arch) for arch in sys.argv[1].split(",")]
SUPPORT_SM80 = any(arch >= 80 for arch in ARCHS)
SUPPORT_SM75 = 75 in ARCHS

FILE_HEAD_COMMENT = """// auto generated by generate_minimal_kernels.py
// clang-format off
"""

FILE_HEAD = (
    FILE_HEAD_COMMENT
    + """
#include "kernel.h"
#include "marlin_template.h"

namespace MARLIN_NAMESPACE_NAME {
"""
)

THREAD_CONFIGS = [(128, 128, 256), (64, 256, 256), (64, 128, 128), (128, 64, 128)]
THREAD_M_BLOCKS = [0.5, 1, 2, 3, 4]
GROUP_BLOCKS = [-1, 8]


def remove_old_kernels():
    base = os.path.dirname(__file__)
    for pattern in ("sm75_kernel_*_u8b128_*.cu", "sm80_kernel_*_u8b128_*.cu"):
        for filename in glob.glob(os.path.join(base, pattern)):
            os.remove(filename)
    selector = os.path.join(base, "kernel_selector.h")
    if os.path.exists(selector):
        os.remove(selector)


def emit_kernel_decl(
    a_type: str,
    c_type: str,
    threads: int,
    thread_m_blocks: int,
    thread_n_blocks: int,
    thread_k_blocks: int,
    m_block_size_8: str,
    stages: int,
    group_blocks: int,
) -> str:
    return (
        "template __global__ void Marlin<"
        f"vllm::{a_type}.id(), "
        "vllm::kU8B128.id(), "
        f"vllm::{c_type}.id(), "
        f"vllm::{c_type}.id(), "
        f"{threads}, {thread_m_blocks}, {thread_n_blocks}, {thread_k_blocks}, "
        f"{m_block_size_8}, {stages}, {group_blocks}, false>"
        "( MARLIN_KERNEL_PARAMS );"
    )


def emit_selector_condition(
    a_type: str,
    c_type: str,
    threads: int,
    thread_m_blocks: int,
    thread_n_blocks: int,
    thread_k_blocks: int,
    m_block_size_8: str,
    stages: int,
    group_blocks: int,
) -> str:
    conditions = [
        f"a_type == vllm::{a_type}",
        "b_type == vllm::kU8B128",
        f"c_type == vllm::{c_type}",
        f"s_type == vllm::{c_type}",
        f"threads == {threads}",
        f"thread_m_blocks == {thread_m_blocks}",
        f"thread_n_blocks == {thread_n_blocks}",
        f"thread_k_blocks == {thread_k_blocks}",
        f"m_block_size_8 == {m_block_size_8}",
        f"stages == {stages}",
        f"group_blocks == {group_blocks}",
        "is_zp_float == false",
    ]
    instantiation = (
        "Marlin<"
        f"vllm::{a_type}.id(), vllm::kU8B128.id(), "
        f"vllm::{c_type}.id(), vllm::{c_type}.id(), "
        f"{threads}, {thread_m_blocks}, {thread_n_blocks}, {thread_k_blocks}, "
        f"{m_block_size_8}, {stages}, {group_blocks}, false>;"
    )
    return " && ".join(conditions), instantiation


def iter_configs(stages: int):
    for m_blocks in THREAD_M_BLOCKS:
        for thread_k, thread_n, threads in THREAD_CONFIGS:
            if threads == 256:
                if m_blocks <= 1 and (thread_k, thread_n) != (128, 128):
                    continue
                if m_blocks > 1 and (thread_k, thread_n) != (64, 256):
                    continue
            for group_blocks in GROUP_BLOCKS:
                yield {
                    "threads": threads,
                    "thread_m_blocks": max(int(m_blocks), 1),
                    "thread_n_blocks": thread_n // 16,
                    "thread_k_blocks": thread_k // 16,
                    "m_block_size_8": "true" if m_blocks == 0.5 else "false",
                    "stages": stages,
                    "group_blocks": group_blocks,
                }


def write_kernel_file(prefix: str, a_type: str, c_type: str, stages: int):
    filename = f"{prefix}_kernel_{a_type[1:]}_u8b128_{c_type[1:]}.cu".lower()
    base = os.path.dirname(__file__)
    lines = [FILE_HEAD, ""]
    for cfg in iter_configs(stages):
        lines.append(
            emit_kernel_decl(
                a_type,
                c_type,
                cfg["threads"],
                cfg["thread_m_blocks"],
                cfg["thread_n_blocks"],
                cfg["thread_k_blocks"],
                cfg["m_block_size_8"],
                cfg["stages"],
                cfg["group_blocks"],
            )
        )
    lines.append("")
    lines.append("}")
    with open(os.path.join(base, filename), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def write_selector():
    selector_lines = [FILE_HEAD_COMMENT]
    first = True

    def append_for(a_type: str, c_type: str, stages: int):
        nonlocal first
        for cfg in iter_configs(stages):
            conditions, instantiation = emit_selector_condition(
                a_type,
                c_type,
                cfg["threads"],
                cfg["thread_m_blocks"],
                cfg["thread_n_blocks"],
                cfg["thread_k_blocks"],
                cfg["m_block_size_8"],
                cfg["stages"],
                cfg["group_blocks"],
            )
            selector_lines.append(
                ("if" if first else "else if") + f" ({conditions})\n  kernel = {instantiation}"
            )
            first = False

    if SUPPORT_SM80:
        append_for("kFloat16", "kFloat16", 4)
        append_for("kBFloat16", "kBFloat16", 4)
    if SUPPORT_SM75:
        append_for("kFloat16", "kFloat16", 2)

    with open(
        os.path.join(os.path.dirname(__file__), "kernel_selector.h"),
        "w",
        encoding="utf-8",
    ) as f:
        f.write("\n".join(selector_lines) + "\n")


if __name__ == "__main__":
    remove_old_kernels()
    if SUPPORT_SM80:
        write_kernel_file("sm80", "kFloat16", "kFloat16", 4)
        write_kernel_file("sm80", "kBFloat16", "kBFloat16", 4)
    if SUPPORT_SM75:
        write_kernel_file("sm75", "kFloat16", "kFloat16", 2)
    write_selector()
